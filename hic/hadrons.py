def _two_body_momentum(parent: float, first: float, second: float) -> float:
    value = (parent**2 - (first + second) ** 2) * (parent**2 - (first - second) ** 2)
    return math.sqrt(max(value, 0.0)) / (2.0 * parent)


def _isotropic(rng: np.random.Generator, count: int) -> np.ndarray:
    cos_theta = rng.uniform(-1.0, 1.0, count)
    sin_theta = np.sqrt(1.0 - cos_theta**2)
    phi = rng.uniform(0.0, 2.0 * math.pi, count)
    return np.column_stack((sin_theta * np.cos(phi), sin_theta * np.sin(phi), cos_theta))


def boost(four_momentum: np.ndarray, velocity: np.ndarray) -> np.ndarray:
    """Boost (E, px, py, pz) rows from a frame moving with ``velocity`` (rows) to the lab."""
    beta2 = np.sum(velocity * velocity, axis=1)
    gamma = 1.0 / np.sqrt(np.maximum(1.0 - beta2, 1.0e-300))
    energy = four_momentum[:, 0]
    momentum = four_momentum[:, 1:]
    beta_dot_p = np.sum(velocity * momentum, axis=1)
    factor = np.where(beta2 > 1.0e-300, (gamma - 1.0) * beta_dot_p / np.maximum(beta2, 1.0e-300), 0.0) + gamma * energy
    result = np.empty_like(four_momentum)
    result[:, 0] = gamma * (energy + beta_dot_p)
    result[:, 1:] = momentum + factor[:, None] * velocity
    return result


def _decay_two_body(parents: np.ndarray, masses: tuple[float, float], parent_mass: float, rng: np.random.Generator):
    count = parents.shape[0]
    q = _two_body_momentum(parent_mass, *masses)
    direction = _isotropic(rng, count) * q
    first = np.column_stack((np.full(count, math.hypot(q, masses[0])), direction))
    second = np.column_stack((np.full(count, math.hypot(q, masses[1])), -direction))
    velocity = parents[:, 1:] / parents[:, :1]
    return [boost(first, velocity), boost(second, velocity)]


def _decay_three_body(parents: np.ndarray, masses: tuple[float, float, float], parent_mass: float, rng):
    """Uniform three-body phase space: weight p*(M -> m12 m3) p*(m12 -> m1 m2) in m12."""
    count = parents.shape[0]
    m1, m2, m3 = masses
    low, high = m1 + m2, parent_mass - m3
    grid = np.linspace(low, high, 257)
    weights = np.asarray([_two_body_momentum(parent_mass, g, m3) * _two_body_momentum(g, m1, m2) for g in grid])
    maximum = 1.05 * float(weights.max())
    m12 = np.empty(count)
    todo = np.arange(count)
    while todo.size:
        trial = rng.uniform(low, high, todo.size)
        w = np.asarray([_two_body_momentum(parent_mass, t, m3) * _two_body_momentum(t, m1, m2) for t in trial])
        accepted = rng.uniform(0.0, maximum, todo.size) < w
        m12[todo[accepted]] = trial[accepted]
        todo = todo[~accepted]
    q3 = np.asarray([_two_body_momentum(parent_mass, m, m3) for m in m12])
    q12 = np.asarray([_two_body_momentum(m, m1, m2) for m in m12])
    direction3 = _isotropic(rng, count)
    third = np.column_stack((np.sqrt(q3**2 + m3**2), direction3 * q3[:, None]))
    pair = np.column_stack((np.sqrt(q3**2 + m12**2), -direction3 * q3[:, None]))
    direction1 = _isotropic(rng, count)
    first = np.column_stack((np.sqrt(q12**2 + m1**2), direction1 * q12[:, None]))
    second = np.column_stack((np.sqrt(q12**2 + m2**2), -direction1 * q12[:, None]))
    pair_velocity = pair[:, 1:] / pair[:, :1]
    first = boost(first, pair_velocity)
    second = boost(second, pair_velocity)
    velocity = parents[:, 1:] / parents[:, :1]
    return [boost(first, velocity), boost(second, velocity), boost(third, velocity)]


def decay_all(
    state: np.ndarray,
    four_momentum: np.ndarray,
    rng: np.random.Generator,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Decay every unstable hadron (recursively) until only final states remain.

    Returns (state ids, four-momenta (E, px, py, pz), origin index into the input rows).
    Photons are kept in the output; use ``final_state_mask`` to select hadrons.
    """
    states, _ = hadron_table()
    stable = np.asarray([h.stable for h in states])
    state = np.asarray(state, dtype=np.int64)
    momenta = np.asarray(four_momentum, dtype=np.float64)
    origin = np.arange(state.size)
    for _ in range(10):
        unstable = ~stable[state]
        if not np.any(unstable):
            return state, momenta, origin
        keep_state, keep_momenta, keep_origin = [state[~unstable]], [momenta[~unstable]], [origin[~unstable]]
        for parent_id in np.unique(state[unstable]):
            rows = np.flatnonzero(state == parent_id)
            parent = states[parent_id]
            ratios = np.asarray([r for r, _ in parent.decays])
            choice = rng.choice(len(ratios), size=rows.size, p=ratios / ratios.sum())
            for channel_index, (_, products) in enumerate(parent.decays):
                selected = rows[choice == channel_index]
                if selected.size == 0:
                    continue
                product_masses = tuple(states[p].mass for p in products)
                if len(products) == 2:
                    daughters = _decay_two_body(momenta[selected], product_masses, parent.mass, rng)
                elif len(products) == 3:
                    daughters = _decay_three_body(momenta[selected], product_masses, parent.mass, rng)
                else:
                    raise ValueError(f"{parent.name}: {len(products)}-body decays are not supported")
                for product, daughter in zip(products, daughters):
                    keep_state.append(np.full(selected.size, product))
                    keep_momenta.append(daughter)
                    keep_origin.append(origin[selected])
        state = np.concatenate(keep_state)
        momenta = np.concatenate(keep_momenta)
        origin = np.concatenate(keep_origin)
    raise RuntimeError("decay chains did not terminate")
