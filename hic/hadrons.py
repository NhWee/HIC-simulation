def bessel_k(order: int, z: float) -> float:
    t = np.linspace(0.0, 12.0, 6000)
    return float(np.trapezoid(np.exp(-z * np.cosh(t)) * np.cosh(order * t), t))


def boltzmann_thermodynamics(mass: float, degeneracy: int, temperature: float) -> dict[str, float]:
    """n (1/fm^3), p, e (GeV/fm^3) and s (1/fm^3) of one Boltzmann species at zero chemical potential."""
    t = temperature
    scale = degeneracy / (2.0 * math.pi**2) / HBARC**3
    if mass <= 0.0:
        n = scale * 2.0 * t**3
        e = 3.0 * n * t
    else:
        z = mass / t
        n = scale * mass * mass * t * bessel_k(2, z)
        e = scale * mass * mass * t * (3.0 * t * bessel_k(2, z) + mass * bessel_k(1, z))
    p = n * t
    return {"n": n, "p": p, "e": e, "s": (e + p) / t}


def number_densities(temperature: float, include_photons: bool = False) -> np.ndarray:
    states, _ = hadron_table()
    return np.asarray([
        0.0 if (h.name == "gamma" and not include_photons) else boltzmann_thermodynamics(h.mass, h.degeneracy, temperature)["n"]
        for h in states
    ])


def hrg_thermodynamics(temperature: float) -> dict[str, float]:
    states, _ = hadron_table()
    totals = {"n": 0.0, "p": 0.0, "e": 0.0, "s": 0.0}
    for h in states:
        if h.name == "gamma":
            continue
        for key, value in boltzmann_thermodynamics(h.mass, h.degeneracy, temperature).items():
            totals[key] += value
    return totals


