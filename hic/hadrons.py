@dataclass
class Hadron:
    name: str
    mass: float
    width: float
    degeneracy: int  # 2J + 1 (one charge state)
    charge: int
    baryon: int
    strangeness: int
    isospin: Fraction
    isospin_3: Fraction
    multiplet: str
    decays: list[tuple[float, tuple[int, ...]]] = field(default_factory=list)  # filled after indexing

    @property
    def stable(self) -> bool:
        return not self.decays

    @property
    def display_class(self) -> int:
        if self.baryon != 0:
            return 2
        if self.multiplet in ("K", "anti-K"):
            return 1
        return 0  # pions (and nothing else is final among mesons)


def clebsch_gordan(j1: Fraction, m1: Fraction, j2: Fraction, m2: Fraction, j: Fraction, m: Fraction) -> float:
    """<j1 m1 j2 m2 | j m> (Condon-Shortley), via the Racah formula."""
    if m1 + m2 != m or not abs(j1 - j2) <= j <= j1 + j2:
        return 0.0
    if abs(m1) > j1 or abs(m2) > j2 or abs(m) > j:
        return 0.0
    factorial = lambda x: math.factorial(int(x))
    prefactor = math.sqrt(
        (2 * j + 1)
        * factorial(j + j1 - j2) * factorial(j - j1 + j2) * factorial(j1 + j2 - j)
        / factorial(j1 + j2 + j + 1)
    ) * math.sqrt(
        factorial(j + m) * factorial(j - m) * factorial(j1 - m1) * factorial(j1 + m1)
        * factorial(j2 - m2) * factorial(j2 + m2)
    )
    total = 0.0
    for k in range(0, int(j1 + j2 - j) + 1):
        terms = (k, j1 + j2 - j - k, j1 - m1 - k, j2 + m2 - k, j - j2 + m1 + k, j - j1 - m2 + k)
        if any(t < 0 for t in terms):
            continue
        denominator = 1
        for t in terms:
            denominator *= factorial(t)
        total += (-1) ** k / denominator
    return prefactor * total


def _charge(isospin_3: Fraction, baryon: int, strangeness: int) -> int:
    value = isospin_3 + Fraction(baryon + strangeness, 2)  # Gell-Mann-Nishijima
    assert value.denominator == 1
    return int(value)


def _default_state_name(multiplet: str, charge: int, multiplicity: int) -> str:
    if multiplicity == 1:
        return multiplet
    suffix = {2: "++", 1: "+", 0: "0", -1: "-", -2: "--"}[charge]
    base, paren, rest = multiplet.partition("(")
    return f"{base}{suffix}{paren}{rest}" if paren else f"{base}{suffix}"


@lru_cache(maxsize=1)
def hadron_table() -> tuple[tuple[Hadron, ...], dict[str, int]]:
    """All charge states (particles and antiparticles) with resolved decay channels."""
    multiplets: dict[str, Multiplet] = {m.name: m for m in MULTIPLETS}
    states: list[Hadron] = []
    by_multiplet: dict[str, list[int]] = {}

    def add_multiplet(mult: Multiplet, conjugate: bool) -> None:
        name = f"anti-{mult.name}" if conjugate else mult.name
        sign = -1 if conjugate else 1
        indices = []
        multiplicity = int(2 * mult.isospin + 1)
        for k in range(multiplicity):
            i3 = mult.isospin - k
            charge = sign * _charge(i3, mult.baryon, mult.strangeness)
            base_charge = _charge(i3, mult.baryon, mult.strangeness)
            state_name = mult.state_names.get(base_charge, _default_state_name(mult.name, base_charge, multiplicity))
            if conjugate:
                state_name = _conjugate_name(state_name)
            states.append(
                Hadron(
                    name=state_name,
                    mass=mult.masses.get(base_charge, mult.mass),
                    width=mult.width,
                    degeneracy=int(2 * mult.spin + 1),
                    charge=charge,
                    baryon=sign * mult.baryon,
                    strangeness=sign * mult.strangeness,
                    isospin=mult.isospin,
                    isospin_3=sign * i3,
                    multiplet=name,
                )
            )
            indices.append(len(states) - 1)
        by_multiplet[name] = indices

    for mult in multiplets.values():
        add_multiplet(mult, conjugate=False)
        if not mult.self_conjugate:
            add_multiplet(mult, conjugate=True)
    states.append(Hadron("gamma", 0.0, 0.0, 2, 0, 0, 0, F(0), F(0), "gamma"))
    index = {hadron.name: i for i, hadron in enumerate(states)}
    if len(index) != len(states):
        raise ValueError("duplicate hadron state names")

    def resolve_multiplet(name: str, conjugate: bool) -> str:
        if not conjugate:
            return name
        if name.startswith("anti-"):
            return name[len("anti-"):]
        return name if multiplets[name].self_conjugate else f"anti-{name}"

    for mult in multiplets.values():
        for conjugate in ((False,) if mult.self_conjugate else (False, True)):
            name = f"anti-{mult.name}" if conjugate else mult.name
            for state_index in by_multiplet[name]:
                parent = states[state_index]
                base_charge = -parent.charge if conjugate else parent.charge
                channels: list[tuple[float, tuple[int, ...]]] = []
                for ratio, products in mult.explicit.get(base_charge, ()):
                    names = tuple(_conjugate_name(p) if conjugate else p for p in products)
                    channels.append((ratio, tuple(index[p] for p in names)))
                for ratio, (first, second) in mult.two_body:
                    first_states = by_multiplet[resolve_multiplet(first, conjugate)]
                    second_states = by_multiplet[resolve_multiplet(second, conjugate)]
                    split = []
                    for a in first_states:
                        for b in second_states:
                            weight = clebsch_gordan(
                                states[a].isospin, states[a].isospin_3,
                                states[b].isospin, states[b].isospin_3,
                                parent.isospin, parent.isospin_3,
                            ) ** 2
                            if weight > 1.0e-12:
                                split.append((weight, (a, b)))
                    norm = sum(w for w, _ in split)
                    if norm <= 0.0:
                        raise ValueError(f"isospin forbids {parent.name} -> {first} {second}")
                    channels.extend((ratio * w / norm, pair) for w, pair in split)
                total = sum(r for r, _ in channels)
                if channels:
                    parent.decays = [(r / total, products) for r, products in channels]
    return tuple(states), index


def _conjugate_name(name: str) -> str:
    special = {"pi+": "pi-", "pi-": "pi+", "K+": "K-", "K-": "K+", "K0": "anti-K0", "anti-K0": "K0",
               "p": "anti-p", "anti-p": "p", "n": "anti-n", "anti-n": "n", "gamma": "gamma",
               "pi0": "pi0", "eta": "eta", "eta'": "eta'", "omega": "omega", "phi": "phi", "rho0": "rho0",
               "f1(1285)": "f1(1285)"}
    if name in special:
        return special[name]
    if name.startswith("anti-"):
        return name[len("anti-"):]
    for a, b in (("++", "--"), ("--", "++")):
        if a in name:
            return "anti-" + name  # doubly charged baryons only occur as Delta
    return "anti-" + name


def final_state_mask() -> np.ndarray:
    states, _ = hadron_table()
    return np.asarray([h.stable and h.name != "gamma" for h in states])


